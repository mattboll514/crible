/// Opens `records.sqlite` for reading.
fn open_records(records: &Path) -> Connection {
    let connection = Connection::open_with_flags(records, OpenFlags::SQLITE_OPEN_READ_ONLY)
        .unwrap_or_else(|error| panic!("{} must be readable: {error}", records.display()));
    connection
        .busy_timeout(Duration::from_millis(1_000))
        .unwrap_or_else(|error| panic!("the busy timeout must be settable: {error}"));
    connection
}

fn count(connection: &Connection, sql: &str) -> u64 {
    let result: i64 = connection
        .query_row(sql, [], |row| row.get(0))
        .unwrap_or_else(|error| panic!("the count query '{sql}' must run: {error}"));
    u64::try_from(result).unwrap_or_else(|_| panic!("the count of '{sql}' must not be negative"))
}

/// Logical state of `records.sqlite`: the values a rejected batch must leave
/// untouched, whatever SQLite does to its pages or its WAL.
#[derive(Debug, Clone, PartialEq, Eq)]
struct DbState {
    generation: u64,
    next_iid: u64,
    documents: u64,
    passages: u64,
    segments: u64,
    batches: u64,
    digest: String,
}

/// Rows a rejected batch must not add, touch or remove.
const DUMP_QUERIES: [&str; 4] = [
    "SELECT generation, epoch, format_version, next_iid FROM meta",
    "SELECT batch_id, generation, manifest_blake3 FROM batches ORDER BY batch_id",
    "SELECT doc_id, doc_hash, fields FROM documents ORDER BY doc_id",
    "SELECT iid, doc_id, ord, created_generation, dead_since_gen FROM passages ORDER BY iid",
];

/// Hashes every row of the result of `sql`, in the order the query returns them.
fn digest_rows(connection: &Connection, sql: &str, hasher: &mut blake3::Hasher) -> u64 {
    let mut statement = connection
        .prepare(sql)
        .unwrap_or_else(|error| panic!("the query '{sql}' must prepare: {error}"));
    let columns = statement.column_count();
    let mut rows = statement
        .query([])
        .unwrap_or_else(|error| panic!("the query '{sql}' must run: {error}"));
    let mut rows_read = 0_u64;
    while let Some(row) = rows
        .next()
        .unwrap_or_else(|error| panic!("a row of '{sql}' must be readable: {error}"))
    {
        rows_read += 1;
        for index in 0..columns {
            let value = row
                .get_ref(index)
                .unwrap_or_else(|error| panic!("a column of '{sql}' must be readable: {error}"));
            match value {
                ValueRef::Null => {
                    hasher.update(b"null\x01");
                }
                ValueRef::Integer(number) => {
                    hasher.update(b"int\x01");
                    hasher.update(number.to_string().as_bytes());
                    hasher.update(b"\x01");
                }
                ValueRef::Real(number) => {
                    hasher.update(b"real\x01");
                    hasher.update(format!("{number:?}").as_bytes());
                    hasher.update(b"\x01");
                }
                ValueRef::Text(text) => {
                    hasher.update(b"text\x01");
                    hasher.update(text);
                    hasher.update(b"\x01");
                }
                ValueRef::Blob(bytes) => {
                    hasher.update(b"blob\x01");
                    hasher.update(bytes);
                    hasher.update(b"\x01");
                }
            }
        }
        hasher.update(b"\x02");
    }
    rows_read
}

fn db_state(fixture: &Fixture) -> DbState {
    let records = records_path(fixture);
    let connection = open_records(&records);
    let mut hasher = blake3::Hasher::new();
    for sql in DUMP_QUERIES {
        digest_rows(&connection, sql, &mut hasher);
    }
    DbState {
        generation: count(&connection, "SELECT generation FROM meta WHERE id = 1"),
        next_iid: count(&connection, "SELECT next_iid FROM meta WHERE id = 1"),
        documents: count(&connection, "SELECT count(*) FROM documents"),
        passages: count(&connection, "SELECT count(*) FROM passages"),
        segments: count(&connection, "SELECT count(*) FROM segments"),
        batches: count(&connection, "SELECT count(*) FROM batches"),
        digest: hasher.finalize().to_hex().to_string(),
    }
}

// --- Files of the index that a rejected batch must not touch ---

/// Every file of the index except the SQLite database and its WAL companions,
/// which `db_state` covers logically, with the digest of its contents.
fn index_files(fixture: &Fixture) -> Vec<(String, String)> {
    let index = fixture.data.join("indexes").join(INDEX);
    let mut files = Vec::new();
    collect_files(&index, &index, &mut files);
    files.sort();
    files
}

fn collect_files(root: &Path, directory: &Path, files: &mut Vec<(String, String)>) {
    let entries = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("{} must be listable: {error}", directory.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| panic!("an entry must be readable: {error}"));
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if path.is_dir() {
            collect_files(root, &path, files);
            continue;
        }
        if name == "records.sqlite" || name == "records.sqlite-wal" || name == "records.sqlite-shm"
        {
            continue;
        }
        let bytes = fs::read(&path)
            .unwrap_or_else(|error| panic!("{} must be readable: {error}", path.display()));
        let relative = path
            .strip_prefix(root)
            .unwrap_or_else(|error| {
                panic!("{} is under {}: {error}", path.display(), root.display())
            })
            .to_string_lossy()
            .into_owned();
        files.push((relative, blake3::hash(&bytes).to_hex().to_string()));
    }
}

/// Every path, relative to the index, whose name announces a temporary file.
fn temporary_entries(fixture: &Fixture) -> Vec<String> {
    let index = fixture.data.join("indexes").join(INDEX);
    let mut found = Vec::new();
    collect_temporary(&index, &index, &mut found);
    found.sort();
    found
}

fn collect_temporary(root: &Path, directory: &Path, found: &mut Vec<String>) {
    let entries = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("{} must be listable: {error}", directory.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| panic!("an entry must be readable: {error}"));
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.starts_with("tmp-") {
            let relative = path
                .strip_prefix(root)
                .unwrap_or_else(|error| {
                    panic!("{} is under {}: {error}", path.display(), root.display())
                })
                .to_string_lossy()
                .into_owned();
            found.push(relative);
        }
        if path.is_dir() {
            collect_temporary(root, &path, found);
        }
    }
}

