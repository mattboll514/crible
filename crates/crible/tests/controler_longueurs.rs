// --- INV-11: the error names the offending keys, at most twenty, in order ---

/// Twenty-five over-long passages: the refusal lists the first twenty keys in a
/// deterministic order, and the attach is deterministic when replayed.
#[test]
fn inv_11_the_error_names_the_first_twenty_offending_keys_in_a_stable_order() {
    let fixture = prepare(None);
    let max = max_tokens(&fixture.models);
    create_index(&fixture);

    let ids: Vec<String> = (0..25).map(|index| format!("fautif-{index:02}")).collect();
    let documents: Vec<(&str, &str)> = ids.iter().map(|id| (id.as_str(), "hash")).collect();
    let overlong = words(max);
    let passages: Vec<(&str, u32, &str)> = ids
        .iter()
        .map(|id| (id.as_str(), 0, overlong.as_str()))
        .collect();
    let batch = write_batch(
        &fixture.root().join("batches"),
        "vingt-cinq-fautifs",
        &documents,
        &passages,
    );

    let first = attach_refused_for_length(&fixture, &batch);
    for id in ids.iter().take(20) {
        assert!(
            first.contains(id),
            "the refusal must name the offending passage key {id}: {first}"
        );
    }
    for id in ids.iter().skip(20) {
        assert!(
            !first.contains(id),
            "the refusal must list at most twenty keys, but it names {id}: {first}"
        );
    }

    let mut positions = Vec::new();
    for id in ids.iter().take(20) {
        positions.push(
            first
                .find(id)
                .unwrap_or_else(|| panic!("the refusal must name {id}: {first}")),
        );
    }
    assert!(
        positions.windows(2).all(|pair| pair[0] < pair[1]),
        "the offending keys must be listed in a deterministic order, the order of the \
         batch rows: {first}"
    );

    let second = attach_refused_for_length(&fixture, &batch);
    assert_eq!(
        second, first,
        "the refusal must be deterministic: the same batch gives the same error"
    );
    assert_eq!(
        db_state(&fixture).generation,
        0,
        "the refused batch must not advance the generation (INV-11)"
    );
}

