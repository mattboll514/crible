// --- Files of the index that a refused batch must not touch ---

/// Every file of the index except the SQLite database and its WAL companions,
/// which `db_state` covers logically, with the digest of its contents.
fn index_files(data: &Path) -> Vec<(String, String)> {
    let index = data.join("indexes").join(INDEX);
    let mut files = Vec::new();
    collect_files(&index, &index, &mut files);
    files.sort();
    files
}

fn collect_files(root: &Path, directory: &Path, files: &mut Vec<(String, String)>) {
    let entries = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("{} must be listable: {error}", directory.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| panic!("an entry must be readable: {error}"));
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if path.is_dir() {
            collect_files(root, &path, files);
            continue;
        }
        if name == "records.sqlite" || name == "records.sqlite-wal" || name == "records.sqlite-shm"
        {
            continue;
        }
        let bytes = fs::read(&path)
            .unwrap_or_else(|error| panic!("{} must be readable: {error}", path.display()));
        let relative = path
            .strip_prefix(root)
            .unwrap_or_else(|error| {
                panic!("{} is under {}: {error}", path.display(), root.display())
            })
            .to_string_lossy()
            .into_owned();
        files.push((relative, blake3::hash(&bytes).to_hex().to_string()));
    }
}

/// Every path, relative to the index, whose name announces a temporary file.
fn temporary_entries(data: &Path) -> Vec<String> {
    let index = data.join("indexes").join(INDEX);
    let mut found = Vec::new();
    collect_temporary(&index, &index, &mut found);
    found.sort();
    found
}

fn collect_temporary(root: &Path, directory: &Path, found: &mut Vec<String>) {
    let entries = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("{} must be listable: {error}", directory.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| panic!("an entry must be readable: {error}"));
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.starts_with("tmp-") {
            let relative = path
                .strip_prefix(root)
                .unwrap_or_else(|error| {
                    panic!("{} is under {}: {error}", path.display(), root.display())
                })
                .to_string_lossy()
                .into_owned();
            found.push(relative);
        }
        if path.is_dir() {
            collect_temporary(root, &path, found);
        }
    }
}

/// Entries of the `segments/` directory of the epoch.
fn segments_entries(data: &Path) -> Vec<String> {
    let directory = data
        .join("indexes")
        .join(INDEX)
        .join("epochs")
        .join(EPOCH.to_string())
        .join("segments");
    let mut names: Vec<String> = fs::read_dir(&directory)
        .unwrap_or_else(|error| panic!("{} must be listable: {error}", directory.display()))
        .map(|entry| {
            entry
                .unwrap_or_else(|error| panic!("a segment entry must be readable: {error}"))
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    names.sort();
    names
}

/// Everything a refused batch must leave untouched, compared before and after.
struct IndexState {
    database: DbState,
    files: Vec<(String, String)>,
    segments: Vec<String>,
}

fn index_state(data: &Path) -> IndexState {
    IndexState {
        database: db_state(data),
        files: index_files(data),
        segments: segments_entries(data),
    }
}

/// Asserts that a refused batch changed nothing in the index (INV-03, INV-12).
fn assert_no_effect(data: &Path, before: &IndexState, context: &str) {
    assert_eq!(
        db_state(data),
        before.database,
        "{context}: a refused batch must leave records.sqlite exactly as it was: no row, no \
         meta change"
    );
    assert_eq!(
        index_files(data),
        before.files,
        "{context}: a refused batch must leave every other file of the index untouched: \
         CURRENT_EPOCH, manifests, segments"
    );
    assert_eq!(
        segments_entries(data),
        before.segments,
        "{context}: a refused batch must not leave a new segment behind"
    );
    assert_eq!(
        temporary_entries(data),
        Vec::<String>::new(),
        "{context}: a refused batch must leave no temporary file in the index"
    );
}

// --- Premises of the fixture, provable without ONNX Runtime ---

/// The premise of the refusal test: the fake model encoded without the prompt
/// really produces a vector whose cosine with the re-encoded one is under 0.999.
///
/// The check compares the vector of the batch, encoded without the prompt, with
/// the fp32 re-encoding of the text with `document: `. For `tribunal` (id 14),
/// the mean of the ids moves from 14 to 8, and the cosine falls to about 0.983.
#[test]
fn the_no_prompt_fixture_vector_falls_below_the_acceptance_threshold() {
    let vocabulary = vocabulary();
    let with_prompt = fake_vector(&vocabulary, "tribunal", true);
    let without_prompt = fake_vector(&vocabulary, "tribunal", false);
    let measured = cosine(&with_prompt, &without_prompt);
    assert!(
        measured < MIN_COSINE,
        "the fixture must make a batch encoded without the prompt fail the acceptance check: \
         the cosine of the fake graph is {measured}, which must be under {MIN_COSINE}"
    );
    assert!(
        measured < 0.99,
        "the fixture must leave a wide margin under the threshold, not sit at its edge: \
         cosine {measured}"
    );
    let itself = cosine(&with_prompt, &with_prompt);
    assert!(
        (itself - 1.0).abs() < 1e-9,
        "the cosine of a vector with itself must be 1; got {itself}"
    );
}

/// The premise of the determinism test: the sixteen perturbed vectors have
/// distinct cosines with the re-encoded one, and every one of them stays above
/// the threshold.
#[test]
fn the_determinism_fixture_vectors_stay_above_the_threshold_and_differ() {
    let vocabulary = vocabulary();
    let base = fake_vector(&vocabulary, "droit", true);
    let expected: Vec<f64> = (0..16)
        .map(|index| {
            let delta = 0.0025 * (index + 1) as f64;
            let perturbed = perturbed_vector(&base, delta);
            let cosine = cosine(&perturbed, &base);
            let theoretical = 1.0 / (1.0 + delta * delta).sqrt();
            assert!(
                (cosine - theoretical).abs() < 1e-6,
                "the perturbation of {delta} must turn the vector by the angle it announces: \
                 got {cosine}, expected about {theoretical}"
            );
            cosine
        })
        .collect();
    assert!(
        expected.iter().all(|cosine| *cosine > MIN_COSINE),
        "every perturbed vector must stay acceptable, otherwise the determinism test could not \
         tell a draw from a refusal: {expected:?}"
    );
    for pair in expected.windows(2) {
        assert!(
            pair[1] < pair[0],
            "the perturbed vectors must have strictly decreasing cosines, so the drawn passage \
             can be read from `min_cosine`: {expected:?}"
        );
    }
}

