//! `RECETTE-IMPORT` (phase P2): the acceptance check at attach (**INV-12**).
//!
//! References: `docs/phases/P2-encodeur-et-recette.md` (task `RECETTE-IMPORT`),
//! `docs/08-invariants-et-tests.md` (INV-10, INV-12),
//! `docs/04-donnees-et-ingestion.md` (control 9 and the attach contract: a
//! refused batch has no effect), `docs/05-api.md` (report shape: `acceptance`
//! with `sample`, `min_cosine`, `p1`, `p50`), ADR-0052 (`acceptance_min_cosine =
//! 0.999` is definitive), ADR-0053 (control 9 lives in `crible-store::attach`,
//! the model is loaded and provided by the caller, after validation and before
//! any write, as control 8) and ADR-0054 (the caller provides a loader; a
//! sample size of zero is refused at configuration, never at attach).
//!
//! # What each test pins
//!
//! | Test | Criterion or invariant |
//! |---|---|
//! | `inv_10_a_replayed_onnx_attach_returns_the_acceptance_statistics` | INV-10: attaching the same `onnx` batch twice writes nothing and returns the stored report, `acceptance` included |
//! | `inv_12_a_batch_encoded_with_the_document_prompt_is_accepted_with_its_distribution` | First acceptance criterion: a batch whose vectors came out of the encoder with `prompt_document` is accepted, and the persisted report carries `sample`, `min_cosine`, `p1` and `p50` |
//! | `inv_12_a_batch_encoded_without_the_document_prompt_is_rejected_without_any_effect` | INV-12 and second acceptance criterion: one passage re-encoded without the prompt pulls the minimum under 0.999, the batch is refused with `acceptance_failed`, and the index keeps its generation, its SQLite rows, its segments and no temporary file |
//! | `inv_12_a_batch_announcing_another_model_is_rejected_without_any_effect` | INV-12 and third acceptance criterion: a manifest announcing another model is refused with `incompatible_model`, before any acceptance check and without any effect |
//! | `inv_12_the_acceptance_sample_is_deterministic_per_batch_id` | The sample is drawn from a seed derived from `batch_id`: the same `batch_id` samples the same passage, two `batch_id`s do not always sample the same one |
//! | `inv_12_an_external_model_has_no_acceptance_check` | Fourth deliverable: an `external` model has no recipe, so a batch of arbitrary vectors is accepted and the report carries no acceptance statistics |
//! | `inv_12_the_legifacile_sample_passes_the_acceptance_check` | First acceptance criterion on real data: the Legifacile sample (`data/legifacile-sample/`) with the real model (`data/models/mdenseon/`) passes the check |
//! | `inv_12_the_legifacile_sample_test_fails_without_its_prerequisites` | ADR-0057: the sample test fails, with the command that builds its data, instead of returning silently when the gitignored data is absent |
//! | `the_no_prompt_fixture_vector_falls_below_the_acceptance_threshold` | Premise of the refusal test: the vector of the fake model encoded without the prompt really is under 0.999 |
//! | `the_determinism_fixture_vectors_stay_above_the_threshold_and_differ` | Premise of the determinism test: the sixteen perturbed vectors are distinct and still above 0.999 |
//!
//! # Why the CLI
//!
//! The check is driven through `crible attach`, the only entry point of P2, so
//! the tests pin behaviour and not an internal API: `crible index create` then
//! `crible attach --data <dir> --models <dir> --index <i> <batch-dir>`. The
//! report is read from `batches.report`, which `docs/04` says carries the
//! acceptance statistics and `docs/05` describes as
//! `acceptance: {sample, min_cosine, p1, p50}`.
//!
//! # Model and vectors
//!
//! The fake encoder of `crates/crible-encode/tests/fixtures/fake-model`
//! (regenerated by `tools/fake_encoder.py`) makes the expected vectors
//! computable without ONNX Runtime: its tokenizer is a lowercased WordLevel with
//! a `WhitespaceSplit` pre-tokenizer, no post-processor and no truncation, and
//! its fp32 graph returns `[mean of the input ids, 1, 1, …]` on every row.
//! CLS pooling keeps `[mean, 1, …, 1]`, and the engine normalizes it, so a
//! passage whose `text` is `t` must be stored as
//! `normalize([mean(ids("document: " + t)), 1, …, 1])`. A batch encoded
//! **without** the prompt stores `normalize([mean(ids(t)), 1, …, 1])`, which the
//! check compares with the re-encoded vector. `tools/fake_encoder.py` is the
//! authority for the graph and the vocabulary; the tests read the vocabulary
//! from the versioned `tokenizer.json`, never a copy of it.
//!
//! # ONNX Runtime
//!
//! Control 9 re-encodes in ONNX fp32, so every test that expects an acceptance
//! decision needs ONNX Runtime, loaded dynamically from `ORT_DYLIB_PATH`
//! (`tools/README.md`); CI has none. Those tests are `#[ignore]`d:
//!
//! ```sh
//! ORT_DYLIB_PATH=/path/to/libonnxruntime.dylib \
//!   cargo test -p crible --test recette_import -- --ignored
//! ```
//!
//! Four tests run in CI. `incompatible_model` is control 3, which needs the
//! manifest and `model.json` only. The `external` test needs no encoder at all.
//! The two premise tests compute the expected vectors of the fake graph in Rust.
//!
//! # What the implementation does
//!
//! Control 9 lives in `crible-store::attach`, after `validate()` and control 8,
//! before any write. It draws a deterministic sample from `batch_id`, re-encodes
//! it in fp32 with `prompt_document`, refuses the batch with
//! `acceptance_failed` below `acceptance_min_cosine`, and stores
//! `acceptance {sample, min_cosine, p1, p50}` in `batches.report`, which a replay
//! returns unchanged (INV-10). An `external` model has no check, and a batch
//! without a passage carries no statistics.

