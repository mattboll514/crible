#![allow(clippy::panic)]

//! Loading of an ONNX encoder (`CHARGER-MODELE`, phase P2).
//!
//! Two acceptance criteria are checked here:
//!
//! - a model file whose content changed is refused, because its blake3 no
//!   longer matches the digest declared by `model.json`;
//! - the vector of 20 reference texts equals the one of
//!   `tools/export_onnx.py` in fp32, within 1e-4.
//!
//! The second criterion needs the model directory of `data/models/mdenseon/`
//! (gitignored) and ONNX Runtime through `ORT_DYLIB_PATH`. CI has neither, so
//! those tests are `#[ignore]`d: they show as ignored instead of passing
//! without checking anything. `tools/README.md` gives the local command that
//! runs them. The fixture is versioned and regenerated by
//! `cd tools && uv run python reference_vectors.py`.

use std::path::{Path, PathBuf};
use std::sync::{Arc, Barrier};

use crible_core::error::ErrorCode;
use crible_encode::{Model, ModelRegistry, Side};

const DIMS: usize = 4;
const FP32_NAME: &str = "model.onnx";
const TOKENIZER_NAME: &str = "tokenizer.json";
const REFERENCE_TEXTS: usize = 20;
/// Tolerance of the acceptance criterion, on every component.
const MAX_COMPONENT_GAP: f32 = 1e-4;

fn blake3_hex(bytes: &[u8]) -> String {
    blake3::hash(bytes).to_hex().to_string()
}

/// Writes a model directory with the given file contents and returns its path.
///
/// The `model.json` declares the blake3 of `fp32` and `tokenizer` as written,
/// so the directory is consistent until a test changes one of them.
fn write_model_directory(
    fp32_contents: &[u8],
    tokenizer_contents: &[u8],
) -> (tempfile::TempDir, PathBuf) {
    let directory = tempfile::tempdir()
        .unwrap_or_else(|error| panic!("a temporary directory is created: {error}"));
    let root = directory.path().to_path_buf();
    std::fs::write(root.join(FP32_NAME), fp32_contents)
        .unwrap_or_else(|error| panic!("model.onnx is written: {error}"));
    std::fs::write(root.join(TOKENIZER_NAME), tokenizer_contents)
        .unwrap_or_else(|error| panic!("tokenizer.json is written: {error}"));
    let model_json = format!(
        r#"{{
  "name": "synthetic",
  "kind": "onnx",
  "hf_id": "lightonai/mDenseOn",
  "revision": "a5fdb000f7a21da96c3bddde3a782ef777316df3",
  "dims": {DIMS},
  "pooling": "cls",
  "normalize": true,
  "max_tokens": 8192,
  "prompts": {{ "query": "query: ", "document": "document: " }},
  "files": {{
    "fp32": {{ "path": "{FP32_NAME}", "blake3": "{}" }},
    "tokenizer": {{ "path": "{TOKENIZER_NAME}", "blake3": "{}" }}
  }}
}}"#,
        blake3_hex(fp32_contents),
        blake3_hex(tokenizer_contents),
    );
    std::fs::write(root.join("model.json"), model_json)
        .unwrap_or_else(|error| panic!("model.json is written: {error}"));
    (directory, root)
}

#[test]
fn refuses_a_model_file_with_a_wrong_hash() {
    // Acceptance criterion: a modified file (wrong hash) is refused. The
    // refusal happens before ONNX Runtime is reached, so this test runs in CI.
    let (_directory, root) = write_model_directory(b"the original graph", b"{}");
    std::fs::write(root.join(FP32_NAME), b"a modified graph").expect("the graph is replaced");

    let error = Model::load(&root).expect_err("a modified model file is refused");

    assert_eq!(error.code(), ErrorCode::InvalidRequest);
    assert!(
        error.message().contains(FP32_NAME),
        "the message names the file: {}",
        error.message()
    );
    assert!(
        error.message().contains("does not match its declared hash"),
        "the message says what is wrong: {}",
        error.message()
    );
}

#[test]
fn refuses_a_tokenizer_with_a_wrong_hash() {
    // The tokenizer is part of the fingerprint, so it is verified too: a
    // tokenizer swapped under a declared hash would encode other ids.
    let (_directory, root) = write_model_directory(b"the original graph", b"{}");
    std::fs::write(root.join(TOKENIZER_NAME), b"{\"other\":\"tokenizer\"}")
        .expect("the tokenizer is replaced");

    let error = Model::load(&root).expect_err("a modified tokenizer is refused");

    assert_eq!(error.code(), ErrorCode::InvalidRequest);
    assert!(
        error.message().contains(TOKENIZER_NAME),
        "the message names the file: {}",
        error.message()
    );
}

/// Directory of the real model.
///
/// Panics with the export command when it is absent: the tests that call it
/// are `#[ignore]`d, so they only run when asked for and must not pretend to
/// pass without their model.
fn real_model_directory() -> PathBuf {
    let directory = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .join("data/models/mdenseon");
    assert!(
        directory.join("model.json").is_file(),
        "{} is missing; export the model before running the ignored tests:\n  cd tools && \
         uv sync --group export && uv run python export_onnx.py --out ../data/models/mdenseon \
         --overwrite",
        directory.display()
    );
    directory
}

/// Reads the versioned fixture: 20 texts and their 20 × 768 fp32 vectors.
fn reference_fixture() -> (Vec<String>, Vec<f32>) {
    let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/mdenseon");
    let texts = std::fs::read_to_string(directory.join("texts.txt"))
        .unwrap_or_else(|error| panic!("the reference texts are versioned: {error}"));
    let texts: Vec<String> = texts.lines().map(str::to_owned).collect();
    assert_eq!(
        texts.len(),
        REFERENCE_TEXTS,
        "the fixture holds the 20 reference texts"
    );

    let raw = std::fs::read(directory.join("vectors.f32"))
        .unwrap_or_else(|error| panic!("the reference vectors are versioned: {error}"));
    let (words, remainder) = raw.as_chunks::<4>();
    assert!(remainder.is_empty(), "vectors.f32 holds whole fp32 words");
    let vectors: Vec<f32> = words.iter().map(|word| f32::from_le_bytes(*word)).collect();
    assert_eq!(
        vectors.len(),
        REFERENCE_TEXTS * 768,
        "the fixture holds one 768-component vector per text, little-endian"
    );
    (texts, vectors)
}

#[test]
#[ignore = "needs data/models/mdenseon and ORT_DYLIB_PATH; run: ORT_DYLIB_PATH=/path/to/libonnxruntime.dylib cargo test -p crible-encode -- --ignored"]
fn loads_a_model_once_per_fingerprint() {
    // Deliverable: the registry loads a model once per fingerprint. Two calls
    // on the same directory return the same encoder, not a second copy.
    let directory = real_model_directory();

    let registry = ModelRegistry::new();
    assert_eq!(registry.loads(), 0, "a new registry has loaded nothing");
    let first = registry
        .get_or_load(&directory)
        .expect("the real model loads");
    assert_eq!(registry.len(), 1, "the first call loads the encoder");
    assert_eq!(registry.loads(), 1, "the first call is one load");
    let second = registry
        .get_or_load(&directory)
        .expect("the cached encoder is served");
    assert!(
        Arc::ptr_eq(&first, &second),
        "the second call returns the loaded encoder instead of loading another"
    );
    assert_eq!(registry.len(), 1, "the registry still holds one encoder");
    assert_eq!(
        registry.loads(),
        1,
        "serving a fingerprint from the cache is not a load"
    );
    assert_eq!(
        first.fingerprint(),
        second.fingerprint(),
        "both calls see the same fingerprint"
    );
}

#[test]
#[ignore = "needs data/models/mdenseon and ORT_DYLIB_PATH; run: ORT_DYLIB_PATH=/path/to/libonnxruntime.dylib cargo test -p crible-encode -- --ignored"]
fn loads_a_model_once_when_callers_race() {
    // The registry holds its lock while loading, so eight callers that start
    // together load the encoder once and all receive the same `Arc`.
    let directory = real_model_directory();
    let registry = Arc::new(ModelRegistry::new());
    let barrier = Arc::new(Barrier::new(8));
    let handles: Vec<_> = (0..8)
        .map(|_| {
            let registry = Arc::clone(&registry);
            let directory = directory.clone();
            let barrier = Arc::clone(&barrier);
            std::thread::spawn(move || {
                barrier.wait();
                registry.get_or_load(&directory)
            })
        })
        .collect();
    let models: Vec<Arc<Model>> = handles
        .into_iter()
        .map(|handle| {
            handle
                .join()
                .expect("the thread does not panic")
                .expect("the real model loads")
        })
        .collect();

    assert_eq!(registry.loads(), 1, "eight racers load the encoder once");
    assert_eq!(registry.len(), 1, "the registry holds one encoder");
    assert!(
        models.iter().all(|model| Arc::ptr_eq(&models[0], model)),
        "every caller receives the same encoder"
    );
}

#[test]
#[ignore = "needs data/models/mdenseon and ORT_DYLIB_PATH; run: ORT_DYLIB_PATH=/path/to/libonnxruntime.dylib cargo test -p crible-encode -- --ignored"]
fn matches_the_python_fp32_vectors_within_1e_4() {
    // Acceptance criterion: the vector produced for the 20 reference texts
    // equals the one of `tools/export_onnx.py` in fp32, within 1e-4.
    let (texts, reference) = reference_fixture();
    let directory = real_model_directory();

    let model = Model::load(&directory).expect("the real model loads");
    assert_eq!(model.dims(), 768);

    let mut worst_gap = 0.0_f32;
    let mut worst_text = 0;
    for (index, text) in texts.iter().enumerate() {
        let vector = model
            .encode(Side::Document, text)
            .expect("the document is encoded");
        assert_eq!(vector.len(), 768, "text {index} has a 768-component vector");
        let expected = &reference[index * 768..(index + 1) * 768];
        for (component, (got, want)) in vector.iter().zip(expected).enumerate() {
            let gap = (got - want).abs();
            assert!(
                gap <= MAX_COMPONENT_GAP,
                "text {index}, component {component}: {got} differs from {want} by {gap}, \
                 above {MAX_COMPONENT_GAP}"
            );
            if gap > worst_gap {
                worst_gap = gap;
                worst_text = index;
            }
        }
    }
    eprintln!("max component gap over {REFERENCE_TEXTS} texts: {worst_gap} (text {worst_text})");
}
