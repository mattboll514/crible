#![allow(clippy::panic)]

//! `ACCELERER-RECETTE` (phase P4, added by ADR-0067): the token count does not
//! change (**INV-11**).
//!
//! References: `docs/phases/P4-recherche-rapide.md` (task `ACCELERER-RECETTE`),
//! `docs/08-invariants-et-tests.md` (INV-11), `docs/04-donnees-et-ingestion.md`
//! (control 8), ADR-0067 (batching the re-encoding of the acceptance check by
//! sorted length).
//!
//! # What each test pins
//!
//! | Test | Prerequisite | Criterion or invariant |
//! |---|---|---|
//! | `inv_11_the_token_count_of_a_passage_does_not_depend_on_the_other_passages` | versioned fixture | INV-11: the count of a passage is the number of ids of `document: <text>`, with no padding, and the same alone or inside a slice, in either order |
//! | `inv_11_the_real_model_token_count_of_the_reference_texts_is_pinned` | `data/models/mdenseon` | INV-11: the count of the twenty versioned reference texts is pinned, so batching the encoder cannot change what control 8 and the acceptance check read |
//!
//! # Why the count is pinned here
//!
//! Control 8 of `docs/04` refuses an over-long passage with
//! `TokenCounter::count_documents`, and the acceptance check re-encodes a
//! sample through `Model::encode`, whose input is `document: <text>` tokenized
//! by the same `tokenize` function. Batching the re-encoding by length adds
//! padding and an attention mask to the ONNX inputs; neither may reach the
//! count, and neither may truncate a passage. Pinning the exact counts of
//! versioned texts is what makes "the token count does not change" checkable
//! (INV-11), independently of the vectors, which the criterion of
//! `ACCELERER-RECETTE` pins separately at 1e-6.
//!
//! The fixture tokenizer is a `WordLevel` with a `WhitespaceSplit`
//! pre-tokenizer, no post-processor and no truncation, so its count is the
//! number of whitespace-separated words plus one for the `document: ` prompt
//! and needs no ONNX Runtime: that test runs in CI.
//!
//! # The real model
//!
//! `inv_11_the_real_model_token_count_of_the_reference_texts_is_pinned` reads
//! `data/models/mdenseon` (gitignored) and, like the other tests of that model,
//! is `#[ignore]`d (ADR-0057). It needs the tokenizer only, not ONNX Runtime.
//! Build the model with:
//!
//! ```sh
//! cd tools && uv sync --group export && uv run python export_onnx.py \
//!   --out ../data/models/mdenseon --overwrite
//! ```
//!
//! and run it with:
//!
//! ```sh
//! cargo test -p crible-encode --test accelere_recette -- --ignored
//! ```

use std::path::{Path, PathBuf};

use crible_encode::TokenCounter;
use tokenizers::Tokenizer;

/// Document prompt of the fake model, which control 8 counts.
const PROMPT: &str = "document: ";

/// `max_tokens` declared by the fixture `model.json`.
const FIXTURE_MAX_TOKENS: u32 = 32;

/// `max_tokens` declared by `data/models/mdenseon/model.json`.
const REAL_MAX_TOKENS: u32 = 8192;

/// Number of texts of the versioned reference fixture.
const REFERENCE_TEXTS: usize = 20;

/// Token counts of the twenty versioned reference texts, `document: ` prompt
/// and special tokens included, as `mdenseon` counts them today.
///
/// Measured on 2026-10-27 with the `mdenseon` tokenizer of ADR-0050
/// (`tokenizer.json`, blake3 `8a801317…`). A change of any of these numbers
/// means the token count moved, which INV-11 and the task forbid.
const REFERENCE_COUNTS: [usize; REFERENCE_TEXTS] = [
    69, 44, 28, 49, 233, 147, 241, 241, 26, 26, 244, 279, 216, 28, 244, 184, 275, 46, 161, 121,
];

/// Directory of the versioned fake model.
fn fixture_directory() -> PathBuf {
    let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/fake-model");
    assert!(
        directory.join("model.json").is_file(),
        "{} is missing; the fake model fixture is versioned and regenerated by:\n  \
         cd tools && uv sync --group export && uv run python fake_encoder.py",
        directory.display()
    );
    directory
}

/// Directory of the versioned reference texts and vectors of the real model.
fn reference_directory() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/mdenseon")
}

/// Directory of the real model, which is gitignored.
///
/// Panics with the export command when it is absent: the test that calls it is
/// `#[ignore]`d, so it runs only when asked for and must not pretend to pass
/// without its model (ADR-0057).
fn real_model_directory() -> PathBuf {
    let directory = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .join("data/models/mdenseon");
    assert!(
        directory.join("model.json").is_file(),
        "{} is missing; export the model before running the ignored test:\n  cd tools && \
         uv sync --group export && uv run python export_onnx.py --out ../data/models/mdenseon \
         --overwrite",
        directory.display()
    );
    directory
}

/// Reads the twenty versioned reference texts of the real model.
fn reference_texts() -> Vec<String> {
    let path = reference_directory().join("texts.txt");
    let texts = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("{} must be readable: {error}", path.display()));
    let texts: Vec<String> = texts.lines().map(str::to_owned).collect();
    assert_eq!(
        texts.len(),
        REFERENCE_TEXTS,
        "the fixture holds the twenty reference texts"
    );
    texts
}

/// Number of ids the fixture tokenizer produces for `document: <text>`.
///
/// It is the authority the counter is compared with: the same `tokenize` call
/// gives the ids the encoder feeds to the graph.
fn tokenizer_ids(directory: &Path, text: &str) -> usize {
    let tokenizer = Tokenizer::from_file(directory.join("tokenizer.json"))
        .unwrap_or_else(|error| panic!("the fixture tokenizer must load: {error}"));
    // No truncation: the count must see the whole input (INV-11).
    let encoding = tokenizer
        .encode(format!("{PROMPT}{text}"), true)
        .unwrap_or_else(|error| panic!("the fixture tokenizer must encode a passage: {error}"));
    encoding.get_ids().len()
}

// --- INV-11: the count of one passage does not depend on the slice ---

/// The count of a passage is the number of ids of `document: <text>`, prompt
/// included, with no padding: the same value alone, in a slice, and whatever
/// the order of the other passages.
///
/// This is the count control 8 refuses an over-long batch with, and the one the
/// acceptance check relies on when it re-encodes a sample. A batched encoder
/// that padds its inputs must not let a pad id into this count (INV-11).
#[test]
fn inv_11_the_token_count_of_a_passage_does_not_depend_on_the_other_passages() {
    let directory = fixture_directory();
    let counter = TokenCounter::load(&directory)
        .unwrap_or_else(|error| panic!("the fixture tokenizer must load: {error}"));
    assert_eq!(
        counter.max_tokens(),
        FIXTURE_MAX_TOKENS,
        "the counter must read the `max_tokens` of `model.json`"
    );

    // The fixture vocabulary is `WordLevel` + `WhitespaceSplit`: one id per
    // word, and `document:` is one word. `hors-vocabulaire` is one `[UNK]` id.
    let texts = ["droit", "contrat la", "droit code article hors-vocabulaire"];
    let expected = [2, 3, 5];

    for (text, expected) in texts.iter().zip(expected) {
        let ids = tokenizer_ids(&directory, text);
        assert_eq!(
            ids, expected,
            "the fixture tokenizer must count `document: {text}` as {expected} ids"
        );
        let counted = counter
            .count_document(text)
            .unwrap_or_else(|error| panic!("the counter must count `{text}`: {error}"));
        assert_eq!(
            counted, expected,
            "the counter must return the number of ids of `document: {text}`, with no pad token \
             (INV-11)"
        );
        // A single passage already in a slice: the count cannot depend on the
        // other passages, which is what a batched encoder could break.
        let alone = counter
            .count_documents(&[text])
            .unwrap_or_else(|error| panic!("the counter must count `{text}`: {error}"));
        assert_eq!(
            alone,
            vec![expected],
            "counting one passage must give the same value as `count_document` (INV-11)"
        );
    }

    let all = counter
        .count_documents(&texts)
        .unwrap_or_else(|error| panic!("the counter must count the slice: {error}"));
    assert_eq!(
        all, expected,
        "the counts of a slice must keep the order of the passages and stay the same as alone \
         (INV-11)"
    );

    let reversed: Vec<&str> = texts.iter().rev().copied().collect();
    let reversed_counts = counter
        .count_documents(&reversed)
        .unwrap_or_else(|error| panic!("the counter must count the reversed slice: {error}"));
    let mut expected_reversed = expected;
    expected_reversed.reverse();
    assert_eq!(
        reversed_counts,
        expected_reversed.to_vec(),
        "the order of the passages must not change a count, so batching by length cannot either \
         (INV-11)"
    );
}

// --- INV-11: the real model counts the reference texts as it does today ---

/// The twenty versioned reference texts are counted exactly as they are today
/// by the `mdenseon` tokenizer: `document: ` prompt and special tokens
/// included, with no truncation.
///
/// The counts are pinned, so a change of `tokenize`, of the prompts, of the
/// tokenizer or a pad id leaking into the count fails here (INV-11). The
/// fixture texts come from `tests/fixtures/mdenseon/texts.txt`, whose vectors
/// `matches_the_python_fp32_vectors_within_1e_4` already pins.
#[test]
#[ignore = "needs data/models/mdenseon; run: cargo test -p crible-encode --test accelere_recette -- --ignored"]
fn inv_11_the_real_model_token_count_of_the_reference_texts_is_pinned() {
    let directory = real_model_directory();
    let counter = TokenCounter::load(&directory)
        .unwrap_or_else(|error| panic!("the real tokenizer must load: {error}"));
    assert_eq!(
        counter.max_tokens(),
        REAL_MAX_TOKENS,
        "the counter must read the `max_tokens` of the real `model.json`"
    );

    let texts = reference_texts();
    let counted = counter
        .count_documents(&texts.iter().map(String::as_str).collect::<Vec<_>>())
        .unwrap_or_else(|error| panic!("the counter must count the reference texts: {error}"));

    for (index, (text, expected)) in texts.iter().zip(REFERENCE_COUNTS).enumerate() {
        let ids = tokenizer_ids(&directory, text);
        assert_eq!(
            ids,
            expected,
            "the mdenseon tokenizer must count `document: {}` as {expected} ids; the count is \
             pinned (INV-11)",
            &text[..text.len().min(40)]
        );
        assert_eq!(
            counted[index], expected,
            "the counter must return the pinned count for reference text {index}, with no pad \
             token and no truncation (INV-11)"
        );
    }

    // Every passage is far below `max_tokens`, so no truncation can explain a
    // difference: the counts above are whole inputs.
    assert!(
        counted
            .iter()
            .all(|count| *count <= REAL_MAX_TOKENS as usize),
        "no reference text may reach max_tokens = {REAL_MAX_TOKENS}, which would hide a \
         truncation: {counted:?}"
    );
}
