//! `INV-06`: "Pool ≤ seuil exact ⇒ résultat identique au calcul exact",
//! checked against the numpy reference of `synth-small`, plus the acceptance
//! criteria of the task `RECHERCHER-DENSE-EXACT` (phase P1).
//!
//! References: `docs/08-invariants-et-tests.md` (INV-06),
//! `docs/phases/P1-stockage-et-recherche-exacte.md` (`RECHERCHER-DENSE-EXACT`),
//! `docs/03-recherche.md` ("Branche dense", strategy EXACT), `docs/05-api.md`
//! ("Recherche : réponse"), `tools/README.md` ("Requêtes et résultats
//! attendus").
//!
//! # API under test
//!
//! `crible_search::dense::exact`, as `src/dense/exact.rs` implements it:
//!
//! ```text
//! crible_search::dense::exact::ExactSearcher
//!
//! impl ExactSearcher {
//!     /// Opens one reader per segment, and the payload reader of the epoch.
//!     pub fn open(segments_dir: &Path, segments: &[SegmentMeta],
//!                 records_path: &Path) -> Result<Self, CribleError>;
//!
//!     /// Exact top-k cosine over `pool`, sorted by descending score, ties
//!     /// broken by ascending key `doc_id#ord`.
//!     pub fn top_k(&self, query: &[f32], pool: &Pool, k: usize)
//!         -> Result<Vec<Hit>, CribleError>;
//! }
//!
//! pub struct Hit {
//!     pub doc_id: String,
//!     pub ord: u32,
//!     pub key: String,              // `doc_id#ord`
//!     pub score: f32,               // cosine, computed in f32
//!     pub fields: serde_json::Value, // document fields merged with passage fields
//!     pub text: String,             // exact encoder input, decompressed
//! }
//! ```
//!
//! The pool comes from `crible_search::pool::Pool`, which the `INV-07` tests
//! cover.
//!
//! Points the tests pin and that the implementation respects:
//!
//! - the query vector is normalised in f32 before the dot product, so the score
//!   is the cosine (`docs/03-recherche.md`: "score = produit scalaire =
//!   cosinus"), as `tools/reference_topk.py` does;
//! - the pool is the only input set: a dead passage is never scored, because it
//!   is not in the pool (`Pool` already intersects with the live bitmap);
//! - the slice partitioning of rayon must not change the result: the same keys
//!   and the same scores with one thread and with several;
//! - `k` larger than the pool returns the whole pool; an empty pool returns an
//!   empty vector, not an error.
//!
//! # What each test pins
//!
//! | Test | Criterion |
//! |---|---|
//! | `inv_06_synth_small_200_queries_match_the_numpy_reference` | INV-06, and the three acceptance criteria: same keys, same order, scores within 1e-5 |
//! | `expected_jsonl_holds_the_quasi_equalities_the_tolerance_allows` | the premise of the tolerance: 5 queries under 1e-6, 55 under 1e-5 (`tools/README.md`) |
//! | `tolerance_guards::*` | the tolerance cannot mask a real error |
//!
//! # Dataset
//!
//! The `synth-small` batches `l1`, `l2` and `l3` and the two query files are
//! generated by `tools/gen_synth.py` and `tools/reference_topk.py`; the CI
//! generates them before `cargo test` (`.github/workflows/ci.yml`). `data/` is
//! gitignored, so a missing file is reported with the command that creates it.

