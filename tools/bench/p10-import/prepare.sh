# Preparation of the import campaign of `IMPORTER-BASE-COMPLETE` (P10,
# ADR-0139): the image, the two named volumes, the exchange tree, the API key
# and the server.
#
# Run from the repository root, once:
#
#   sh tools/bench/p10-import/prepare.sh
#
# It refuses to overwrite what it already built and never removes anything.
# The campaign itself is `import.py`, driven by `attach-all.sh`.
#
# What it creates:
#   - image `crible:p10`, built from `docker/Dockerfile` on the current tree;
#   - named volume `crible-p10-data` on `/data` (ADR-0139, decision 5, point 2);
#   - named volume `crible-p10-models` on `/models`, seeded from
#     `data/models/mdenseon`;
#   - the host directory `data/p10-exchange` on `/exchange`, with `inbox/` and
#     `snapshots/` (gitignored);
#   - `data/p10-exchange/crible.toml`, read-only, holding an `admin` key whose
#     digest comes from `crible key generate`; the key itself is written to
#     `data/p10-import/token.txt`, never to a tracked file;
#   - the container `crible-p10-server`, port 18090 on the host.
#
# Every lot is mounted by `attach-all.sh`, directly under `/exchange/inbox`,
# read-only, so that `directory` is a single path component (ADR-0107).

set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../../.." && pwd)
cd "$ROOT"

IMAGE=crible:p10
DATA_VOLUME=crible-p10-data
MODELS_VOLUME=crible-p10-models
CONTAINER=crible-p10-server
EXCHANGE=$ROOT/data/p10-exchange
OUT=$ROOT/data/p10-import
DEBIAN=debian:bookworm-slim

mkdir -p "$EXCHANGE/inbox" "$EXCHANGE/snapshots" "$OUT"

# 1. Space, before anything is written (ADR-0139, decision 1: 130 Go free on
#    the host, read in decimal Go, with the GiB figure published next to it).
{
    date -u +"%Y-%m-%dT%H:%M:%SZ"
    df -h /
    df -H /
} > "$OUT/df-host-prepare.txt"
free_go=$(df -H / | awk 'NR==2 {sub(/G$/, "", $4); print $4}')
echo "host: $free_go Go free"
if [ "$free_go" -lt 130 ]; then
    echo "the host has $free_go Go free, under the 130 Go of ADR-0139" >&2
    exit 1
fi
docker system df > "$OUT/docker-system-df-prepare.txt"

# 2. The image, timed.
start=$(date +%s)
if ! docker build -f docker/Dockerfile -t "$IMAGE" . > "$OUT/build.log" 2>&1; then
    cat "$OUT/build.log" >&2
    exit 1
fi
cat "$OUT/build.log"
end=$(date +%s)
echo "image $IMAGE built in $((end - start)) s" | tee "$OUT/build-time.txt"

# 3. The volumes. A named volume only on `/data` (ADR-0135, decision 3).
for volume in "$DATA_VOLUME" "$MODELS_VOLUME"; do
    if docker volume inspect "$volume" >/dev/null 2>&1; then
        echo "volume $volume already exists, left untouched" >&2
    else
        docker volume create "$volume"
    fi
done

if docker run --rm -v "$MODELS_VOLUME":/models "$DEBIAN" test -f /models/mdenseon/model.json; then
    echo "models already seeded, left untouched" >&2
else
    docker run --rm -v "$MODELS_VOLUME":/models \
        -v "$ROOT/data/models/mdenseon:/src:ro" "$DEBIAN" \
        sh -c 'cp -a /src /models/mdenseon && chown -R 1000:1000 /models'
fi

docker run --rm -v "$DATA_VOLUME":/data "$DEBIAN" sh -c '
    mkdir -p /data/indexes /data/tmp
    chown -R 1000:1000 /data
    df -h /data
    du -sh /data'
docker run --rm -v "$MODELS_VOLUME":/models "$DEBIAN" sh -c 'du -sh /models'

# 4. The key and the configuration. The key is printed once; its digest goes to
#    the configuration, the key to the gitignored output directory.
if [ -f "$OUT/token.txt" ]; then
    echo "key already drawn, kept in $OUT/token.txt" >&2
    digest=$(awk -F': ' '/^sha256:/ {print $2}' "$OUT/key-generate.txt")
else
    docker run --rm "$IMAGE" key generate > "$OUT/key-generate.txt"
    awk -F': ' '/^key:/ {print $2}' "$OUT/key-generate.txt" > "$OUT/token.txt"
    digest=$(awk -F': ' '/^sha256:/ {print $2}' "$OUT/key-generate.txt")
fi

cat > "$EXCHANGE/crible.toml" <<EOF
# Instance of the import campaign of IMPORTER-BASE-COMPLETE (P10, ADR-0139).
# Generated by tools/bench/p10-import/prepare.sh; never committed.

[server]
bind = "0.0.0.0:8080"
search_threads = 0
max_concurrent_searches = 0

[paths]
data = "/data"
models = "/models"
exchange = "/exchange"

[auth]
keys = [
  { name = "p10-import", role = "admin", sha256 = "$digest" },
]

[analytics]
retention_days = 90

[debug_journal]
enabled = false
sample_rate = 0.0
ttl_days = 7
max_rows = 500000
max_bytes = 2147483648

[encoder]
query_precision = "fp32"

[limits]
writer_queue = 16
default_timeout_ms = 2000
wait_timeout_ms = 60000
query_cache_entries = 1024
EOF
chmod 600 "$OUT/token.txt"

# 5. The server, with the six lots mounted read-only, each directly under
#    `/exchange/inbox/<nom>` so that `directory` is a single component
#    (ADR-0139, decision 5, point 2; ADR-0107).
if docker container inspect "$CONTAINER" >/dev/null 2>&1; then
    echo "container $CONTAINER already exists, left untouched" >&2
else
    docker run -d --name "$CONTAINER" -p 18090:8080 --stop-timeout 65 \
        -v "$DATA_VOLUME":/data \
        -v "$MODELS_VOLUME":/models \
        -v "$EXCHANGE":/exchange \
        -v "$EXCHANGE/crible.toml:/etc/crible/crible.toml:ro" \
        -v "$ROOT/data/legifacile-full/dole/dole-full-v1:/exchange/inbox/dole-full-v1:ro" \
        -v "$ROOT/data/legifacile-full/sarde/sarde-full-v1:/exchange/inbox/sarde-full-v1:ro" \
        -v "$ROOT/data/legifacile-full/titres/titres-full-v2:/exchange/inbox/titres-full-v2:ro" \
        -v "$ROOT/data/legifacile-full/jorf/jorf-full-v1:/exchange/inbox/jorf-full-v1:ro" \
        -v "$ROOT/data/legifacile-full/articles/articles-full-v1:/exchange/inbox/articles-full-v1:ro" \
        -v "$ROOT/data/legifacile-full/decisions/decisions-full-v1:/exchange/inbox/decisions-full-v1:ro" \
        "$IMAGE"
fi

# 6. Wait for `/ready` (ADR-0099): the demo timings do not apply to a real
#    instance, so the wait is explicit and bounded.
tries=0
until curl -fsS --max-time 4 http://127.0.0.1:18090/ready >/dev/null 2>&1; do
    tries=$((tries + 1))
    if [ "$tries" -gt 120 ]; then
        echo "the server is not ready after 240 s" >&2
        docker logs --tail 50 "$CONTAINER" >&2
        exit 1
    fi
    sleep 2
done
curl -fsS http://127.0.0.1:18090/health | tee "$OUT/health.json" >/dev/null
curl -fsS http://127.0.0.1:18090/ready | tee "$OUT/ready.json" >/dev/null
docker exec "$CONTAINER" df -h /data | tee "$OUT/df-vm-start.txt"
